package purrfectfit.model;

/**
 * Represents the three categories of clothing available
 * in Purrfect Fit.
 *
 * Each outfit contains exactly one item from each category.
 *
 * @author Lovesh Kataria
 * @version 11.11.2026
 */
public enum ClothingCategory
{
    /**
     * Clothing worn on the head.
     */
    HAT,

    /**
     * Clothing worn on the body.
     */
    TOP,

    /**
     * Clothing worn on the feet.
     */
    SHOES
}
