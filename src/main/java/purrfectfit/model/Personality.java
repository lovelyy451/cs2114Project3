package purrfectfit.model;

/**
 * Represents the different personalities that a customer
 * can have in Purrfect Fit.
 *
 * Each personality determines the style of dialogue
 * generated for a customer.
 *
 * @author Lovesh Kataria
 * @version 11.11.2026
 */
public enum Personality
{
    /**
     * Represents a customer who speaks aggressively.
     */
    AGGRESSIVE,

    /**
     * Represents a customer who speaks kindly.
     */
    KIND,

    /**
     * Represents a customer who speaks impatiently.
     */
    IMPATIENT,

    /**
     * Represents a customer who speaks respectfully.
     */
    RESPECTFUL
}
